// Fixed copies of the version files (and of CHANGELOG.md) that the release script tests work on, so
// no test reads the real CHANGELOG.md or version files, which change with every release. Also the git
// sandbox that every test which runs git uses.
import { spawnSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { delimiter, join } from 'node:path'

const CARGO_T = `[workspace]
members = ["crates/core", "app/src-tauri"]
resolver = "3"

[workspace.package]
edition = "2024"
version = "@VERSION@"

[workspace.dependencies]
serde = { version = "1" }
`
const LOCK_T = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "aho-corasick"
version = "0.1.0"

[[package]]
name = "breccia"
version = "@VERSION@"
dependencies = [
 "breccia-core",
]

[[package]]
name = "breccia-core"
version = "@VERSION@"
dependencies = [
 "serde",
]

[[package]]
name = "zzz"
version = "0.1.0"
`
// The templates mark the app's version with @VERSION@; other 0.1.0 strings (dependencies) stay as they are.
const at = (t, v) => t.replaceAll('@VERSION@', v)
export const CARGO = at(CARGO_T, '0.1.0')
export const LOCK = at(LOCK_T, '0.1.0')
export const TAURI = `{
  "productName": "Breccia",
  "identifier": "dev.breccia.app"
}
`
const PKG_T = `{
  "name": "breccia-app",
  "private": true,
  "version": "@VERSION@",
  "type": "module",
  "dependencies": { "dep": "^1.0.0" }
}
`
const PKG_LOCK_T = `{
  "name": "breccia-app",
  "version": "@VERSION@",
  "lockfileVersion": 3,
  "requires": true,
  "packages": {
    "": {
      "name": "breccia-app",
      "version": "@VERSION@",
      "dependencies": {
        "dep": "^1.0.0"
      }
    },
    "node_modules/dep": {
      "version": "0.1.0",
      "resolved": "x"
    }
  }
}
`
// A sample changelog: the cliff.toml header (as in CHANGELOG.md) plus a 0.1.0 entry.
export const PKG = at(PKG_T, '0.1.0')
export const PKG_LOCK = at(PKG_LOCK_T, '0.1.0')
export const CHANGELOG = [
  '# Changelog',
  '',
  'User-visible changes to Breccia, newest first.',
  '',
  '## [0.1.0] - 2026-10-31',
  '',
  'The first release: a daily journal, pages with `[[links]]` and `#tags`, configurable task states and Kanban boards over every task block, All pages, search (`Ctrl K`), Git sync, five themes and a graph of the links. Windows installer, not code signed.',
  '',
].join('\n')

// Write the five version files (at `version`) and CHANGELOG.md into `dir`.
export function writeFixture(dir, version = '0.1.0') {
  mkdirSync(join(dir, 'app', 'src-tauri'), { recursive: true })
  const files = {
    'Cargo.toml': at(CARGO_T, version),
    'Cargo.lock': at(LOCK_T, version),
    'app/src-tauri/tauri.conf.json': TAURI,
    'app/package.json': at(PKG_T, version),
    'app/package-lock.json': at(PKG_LOCK_T, version),
    'CHANGELOG.md': CHANGELOG,
  }
  for (const [p, c] of Object.entries(files)) writeFileSync(join(dir, p), c)
}

// A temp folder plus a git environment that cannot reach any other repo: no GIT_* variable of the
// caller (GIT_DIR, GIT_WORK_TREE, GIT_INDEX_FILE, ...), its own global config with a test identity,
// no system config, no credential prompts, and the folder as a ceiling. `git(dir, ...)` always
// names its directory. Call `remove()` when done (afterAll).
export function gitSandbox() {
  const root = mkdtempSync(join(tmpdir(), 'breccia-release-'))
  const config = join(root, 'gitconfig')
  writeFileSync(
    config,
    '[user]\n\tname = Breccia Test\n\temail = test@example.invalid\n[commit]\n\tgpgsign = false\n' +
      '[tag]\n\tgpgsign = false\n[init]\n\tdefaultBranch = main\n[core]\n\tautocrlf = false\n',
  )
  const env = Object.fromEntries(Object.entries(process.env).filter(([k]) => !/^GIT_/i.test(k)))
  Object.assign(env, {
    GIT_CONFIG_GLOBAL: config,
    GIT_CONFIG_NOSYSTEM: '1',
    GIT_TERMINAL_PROMPT: '0',
    GIT_CEILING_DIRECTORIES: [root, realpathSync.native(root)].join(delimiter),
  })
  const git = (dir, ...args) => {
    const r = spawnSync('git', ['-C', dir, ...args], { env, encoding: 'utf8' })
    if (r.status !== 0) throw new Error(`git ${args.join(' ')}: ${r.stderr}`)
    return r.stdout
  }
  const remove = () => rmSync(root, { recursive: true, force: true })
  return { root, env, git, remove }
}
