//! The window's TypeScript types (`app/src/lib/generated.ts`) are written from the core's wire types by ts-rs.
//! `just types` writes the file; this test fails when it is out of date.

use std::any::TypeId;
use std::collections::{BTreeMap, HashSet};
use std::path::PathBuf;

use breccia_core::git::GitView;
use breccia_core::session::{
    CommandError, ConfigView, DailyView, ErrorCode, Notice, Output, PageView, RenameView, Request,
    TreeView,
};
use ts_rs::{Config, TS, TypeVisitor};

const HEADER: &str = "// Generated by `just types` from crates/core. Do not edit.\n";

/// Collects the declaration of every type it visits and, through them, of every type they use.
struct Collect<'a> {
    cfg: &'a Config,
    seen: HashSet<TypeId>,
    decls: BTreeMap<String, String>,
}

impl TypeVisitor for Collect<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        // Only derived types have a declaration of their own; strings, numbers, arrays and options do not.
        if T::output_path().is_none() || !self.seen.insert(TypeId::of::<T>()) {
            return;
        }
        let mut decl = T::docs().unwrap_or_default();
        decl.push_str("export ");
        decl.push_str(&T::decl(self.cfg));
        let name = T::ident(self.cfg);
        if let Some(other) = self.decls.insert(name.clone(), decl) {
            panic!("two wire types are both named `{name}`; the other is:\n{other}");
        }
        T::visit_dependencies(self);
    }
}

/// The file as `just types` writes it: the header, then one `export type` per wire type, sorted by name.
fn render() -> String {
    // The core's 64-bit integers (block IDs, generations, versions) stay below 2^53, so they are plain numbers.
    let cfg = Config::new().with_large_int("number");
    let mut collect = Collect {
        cfg: &cfg,
        seen: HashSet::new(),
        decls: BTreeMap::new(),
    };
    // The roots: what the window sends and gets back, and the payloads of the events made from the core's
    // types. `index:changed` carries the shell's own type, so its type stays hand-written in the window.
    collect.visit::<Request>();
    collect.visit::<Output>();
    collect.visit::<CommandError>();
    collect.visit::<PageView>();
    collect.visit::<TreeView>();
    collect.visit::<RenameView>();
    collect.visit::<ConfigView>();
    collect.visit::<DailyView>();
    collect.visit::<Notice>();
    collect.visit::<GitView>();
    let mut out = String::from(HEADER);
    for decl in collect.decls.values() {
        out.push('\n');
        // ts-rs ends each field before a doc comment with a space.
        for line in decl.lines() {
            out.push_str(line.trim_end());
            out.push('\n');
        }
    }
    out
}

/// `ErrorCode::ALL` is kept by hand; ts-rs reads the enum itself, so a code missing from the list shows here.
#[test]
fn error_code_list_names_every_code() {
    let union = ErrorCode::inline(&Config::new());
    let mut from_enum: Vec<&str> = union.split(" | ").map(|s| s.trim_matches('"')).collect();
    from_enum.sort_unstable();
    let mut from_list: Vec<&str> = ErrorCode::ALL.iter().map(|c| c.as_str()).collect();
    from_list.sort_unstable();
    assert_eq!(from_list, from_enum, "ErrorCode::ALL must list every code");
}

fn generated_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../app/src/lib/generated.ts")
}

#[test]
fn generated_types_are_current() {
    let rendered = render();
    let path = generated_path();
    if std::env::var("BRECCIA_WRITE_TYPES").as_deref() == Ok("1") {
        std::fs::write(&path, &rendered).expect("write app/src/lib/generated.ts");
        return;
    }
    let on_disk = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        on_disk == rendered,
        "app/src/lib/generated.ts is out of date: run `just types`"
    );
}
